/**
 * The one place oss-decrypt decides which Ed25519 public key a prompt manifest must be signed with.
 *
 * The key follows the API address the CLI talks to (the value getApiUrl returns), ADR-005 decision 1:
 * - production address              -> production key
 * - staging address, or loopback DEV -> staging key
 * - anything else                    -> refused; prompts are never fetched against an unverifiable manifest
 * A non-production address never gets the production key, and the production address never gets the
 * staging key, so a leaked staging key cannot sign prompts that production users accept.
 */

import crypto from 'crypto';
import { DEFAULT_API_URL, isAcceptedApiUrl } from './config.js';

export interface ManifestKeys {
  /** Base64 SPKI DER Ed25519 public key */
  production: string;
  /** Base64 SPKI DER Ed25519 public key */
  staging: string;
}

/** Staging API address. Placeholder hostname until the staging service exists. */
export const STAGING_API_URL = 'https://one-shot-ship-api-staging.onrender.com';

/** Production manifest public key. Generated by: npm run manifest:generate --generate-keys (API repo). */
export const PRODUCTION_MANIFEST_PUBLIC_KEY = 'MCowBQYDK2VwAyEAAwFG32b8TuiVTxrDnXzNrb2v68YN5U9epLnZ3O7pQaI=';

/**
 * Staging manifest public key. NOT A KEY YET: the maintainer generates the staging pair in Task 11 and
 * puts the public half here. Until then staging and loopback addresses fail closed.
 */
export const STAGING_MANIFEST_PUBLIC_KEY = 'PLACEHOLDER-NOT-A-KEY: staging signing key not generated yet (Task 11)';

export const PINNED_KEYS: ManifestKeys = {
  production: PRODUCTION_MANIFEST_PUBLIC_KEY,
  staging: STAGING_MANIFEST_PUBLIC_KEY,
};

const LOOPBACK_HOSTS = ['localhost', '127.0.0.1', '[::1]'];

const UNTRUSTED_ADDRESS =
  `apiUrl in your OSS config is not an address this oss-decrypt trusts for signed prompts. ` +
  `Accepted: ${DEFAULT_API_URL} (production), ${STAGING_API_URL} (staging), ` +
  `or http://localhost, http://127.0.0.1 or http://[::1] with any port (local development).`;

const STAGING_KEY_MISSING =
  '[SECURITY] staging signing key not configured in this build. Prompt delivery blocked.';

function isEd25519PublicKey(key: string): boolean {
  try {
    const keyObj = crypto.createPublicKey({ key: Buffer.from(key, 'base64'), format: 'der', type: 'spki' });
    return keyObj.asymmetricKeyType === 'ed25519';
  } catch {
    return false;
  }
}

function stagingKey(keys: ManifestKeys): string {
  if (!isEd25519PublicKey(keys.staging)) throw new Error(STAGING_KEY_MISSING);
  return keys.staging;
}

/**
 * The public key a manifest from `apiUrl` must be signed with. The address must pass the shared apiUrl
 * rule (no userinfo, query or fragment) and then match by exact origin; there is no prefix matching.
 *
 * @throws when the address is not production, staging or loopback (message names apiUrl, never echoes it)
 * @throws when the address needs the staging key and this build carries none
 */
export function publicKeyFor(apiUrl: string, keys: ManifestKeys = PINNED_KEYS): string {
  if (!isAcceptedApiUrl(apiUrl)) throw new Error(UNTRUSTED_ADDRESS);
  const url = new URL(apiUrl);
  if (url.origin === DEFAULT_API_URL) return keys.production;
  if (url.origin === STAGING_API_URL) return stagingKey(keys);
  if (url.protocol === 'http:' && LOOPBACK_HOSTS.includes(url.hostname)) return stagingKey(keys);
  throw new Error(UNTRUSTED_ADDRESS);
}
